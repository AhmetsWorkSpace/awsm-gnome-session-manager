'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const source = fs.readFileSync(path.join(__dirname, '..', 'saveSession.js'), 'utf8');
const start = source.indexOf('    _setFieldsFromProcess(');
const end = source.indexOf('    destroy()', start);
assert.ok(start >= 0 && end > start);
let raw;
const Gio = {File: {new_for_path: () => ({load_contents: () => [true, raw]})}};
const Saver = new Function('Gio', `return class { ${source.slice(start, end)} }`)(Gio);
const saver = new Saver();
saver._log = {debug() {}};
raw = new TextEncoder().encode('/path with spaces/app\0argument with spaces\0quote\' and "\0');
const record = {pid: 123, desktop_file_id: ''};
saver._setFieldsFromProcess(null, record);
assert.deepEqual(record.cmd, ['/path with spaces/app', 'argument with spaces', 'quote\' and "']);
assert.equal(record.cmd_argv_verified, true);
raw = new TextEncoder().encode('/partial-without-terminator');
const partial = {pid: 123, desktop_file_id: ''};
saver._setFieldsFromProcess(null, partial);
assert.equal(partial.cmd, null);
const desktop = {pid: 123, desktop_file_id: 'example.desktop'};
saver._setFieldsFromProcess(null, desktop);
assert.equal(desktop.cmd, null);
console.log('[PASS] proc argv boundaries, incomplete data and desktop priority');
